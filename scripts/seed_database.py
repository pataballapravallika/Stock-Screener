def run_seeding():
    print("Seeding company metadata into stock_data.db...")
    for comp in COMPANY_METADATA:
        # Construct shareholding trend table JSON
        sh_trend = [
            {"Category": "Promoter", "Percentage": comp["promoter_pct"], "Period": comp["shareholding_period"]},
            {"Category": "FII", "Percentage": comp["fii_pct"], "Period": comp["shareholding_period"]},
            {"Category": "DII", "Percentage": comp["dii_pct"], "Period": comp["shareholding_period"]},
            {"Category": "Public", "Percentage": comp["public_pct"], "Period": comp["shareholding_period"]},
        ]
        comp_info = dict(comp)
        comp_info["shareholding_json"] = json.dumps(sh_trend)
        save_company_info(comp_info)
        print(f"  [OK] {comp['ticker']}: Sector={comp['sector']}, MarketCap=Rs.{comp['market_cap']:,.0f}Cr, Promoter={comp['promoter_pct']}%")

    print("\nSeeding TATAMOTORS fundamental filings into stock_data.db...")
    for r in TATAMOTORS_REPORTS:
        save_fundamental_report(r)
        print(f"  [OK] TATAMOTORS report {r['period']} ({r['report_date']}): Rev=Rs.{r['revenue']:,.0f}Cr, PAT=Rs.{r['pat']:,.0f}Cr")
    
    save_ttm_record(TATAMOTORS_TTM)
    print("  [OK] TATAMOTORS TTM record saved.")

    print("\nDatabase seeding completed successfully!")


if __name__ == "__main__":
    run_seeding()
